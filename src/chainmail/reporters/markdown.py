"""Markdown audit report, structured like a professional audit deliverable."""

from __future__ import annotations

import time
from collections import defaultdict

from ..engine import ScanResult
from ..findings import Finding, Severity

PREFIX = {
    Severity.CRITICAL: "C",
    Severity.HIGH: "H",
    Severity.MEDIUM: "M",
    Severity.LOW: "L",
    Severity.INFO: "I",
    Severity.GAS: "G",
}
EMOJI = {
    Severity.CRITICAL: "🟥",
    Severity.HIGH: "🟧",
    Severity.MEDIUM: "🟨",
    Severity.LOW: "🟦",
    Severity.INFO: "⬜",
    Severity.GAS: "🟪",
}


def finding_ids(findings: list[Finding]) -> dict[int, str]:
    counters: dict[Severity, int] = defaultdict(int)
    ids: dict[int, str] = {}
    for f in findings:
        counters[f.severity] += 1
        ids[id(f)] = f"{PREFIX[f.severity]}-{counters[f.severity]:02d}"
    return ids


def render_markdown(result: ScanResult) -> str:
    ids = finding_ids(result.findings)
    out: list[str] = []
    out.append("# Smart Contract Audit Report")
    out.append("")
    out.append(f"*Generated by **Chainmail v{result.tool_version}** on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}*")
    out.append("")
    out.append(
        "> Automated static analysis is a starting point, not a substitute for a manual review. "
        "Each finding should be triaged by an auditor."
    )
    out.append("")

    out.append("## Summary")
    out.append("")
    out.append("| Metric | Value |")
    out.append("|---|---|")
    out.append(f"| Files analysed | {len(result.files)} |")
    out.append(f"| Contracts | {result.contracts} |")
    out.append(f"| Functions & modifiers | {result.functions} |")
    out.append(f"| Lines of code | {result.lines_of_code} |")
    out.append(f"| Detectors run | {len(result.detectors_run)} |")
    out.append(f"| Risk score | **{result.risk_score}/100** |")
    out.append("")
    out.append("| Severity | Count |")
    out.append("|---|---:|")
    for sev, n in result.counts.items():
        out.append(f"| {EMOJI[Severity(sev)]} {sev.capitalize()} | {n} |")
    out.append("")

    if result.findings:
        out.append("## Findings overview")
        out.append("")
        out.append("| ID | Title | Severity | Confidence | Location |")
        out.append("|---|---|---|---|---|")
        for f in result.findings:
            loc = f"`{f.location.file}:{f.location.line}`"
            out.append(
                f"| [{ids[id(f)]}](#{ids[id(f)].lower()}) | {f.title} | {f.severity.value.capitalize()} | {f.confidence.value} | {loc} |"
            )
        out.append("")

        out.append("## Detailed findings")
        out.append("")
        for f in result.findings:
            fid = ids[id(f)]
            out.append(f"### {fid}")
            out.append("")
            out.append(f"**{f.title}**")
            out.append("")
            meta = [
                f"**Severity:** {f.severity.value.capitalize()}",
                f"**Confidence:** {f.confidence.value}",
                f"**Detector:** `{f.detector}`",
            ]
            if f.swc:
                meta.append(f"**SWC:** [{f.swc}](https://swcregistry.io/docs/{f.swc})")
            if f.cwe:
                num = f.cwe.split("-")[-1]
                meta.append(f"**CWE:** [{f.cwe}](https://cwe.mitre.org/data/definitions/{num}.html)")
            out.append(" · ".join(meta))
            out.append("")
            scope = f"`{f.location.file}` line {f.location.line}"
            if f.location.contract:
                scope += f" - `{f.location.contract}" + (f".{f.location.function}" if f.location.function else "") + "`"
            out.append(f"**Location:** {scope}")
            out.append("")
            if f.snippet:
                out.append("```solidity")
                out.append(f.snippet)
                out.append("```")
                out.append("")
            out.append("**Description**")
            out.append("")
            out.append(f.description)
            out.append("")
            if f.recommendation:
                out.append("**Recommendation**")
                out.append("")
                out.append(f.recommendation)
                out.append("")
            if f.references:
                out.append("**References:** " + ", ".join(f"<{r}>" for r in f.references))
                out.append("")
            out.append(f"<sub>Fingerprint: `{f.fingerprint}`</sub>")
            out.append("")
    else:
        out.append("## Findings")
        out.append("")
        out.append("No issues were found by the enabled detectors. ✅")
        out.append("")

    out.append("## Scope")
    out.append("")
    for path in result.files:
        out.append(f"- `{path}`")
    out.append("")
    if result.parse_errors:
        out.append("## Parser warnings")
        out.append("")
        out.append("The following constructs could not be parsed and were skipped; results for them may be incomplete.")
        out.append("")
        for path, err in result.parse_errors:
            out.append(f"- `{path}`: {err}")
        out.append("")
    return "\n".join(out)
